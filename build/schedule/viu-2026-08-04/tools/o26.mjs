import {boot,APP} from './boot.mjs';
import fs from 'fs';
const {browser,page}=await boot({tz:'America/Edmonton'});
const E='/tmp/sviu/evidence/'; const F={reqs:[]};
page.on('request',r=>{const u=r.url(); if(u.includes('/api/schedule')&&r.method()!=='GET') F.reqs.push({m:r.method(),u:u.replace(/^https:\/\/[^/]+/,''),body:(r.postData()||'').slice(0,300)});});
page.on('response',async r=>{const u=r.url(); if(u.includes('/api/schedule')&&r.request().method()!=='GET'){try{F.reqs.push({res:r.status(),body:(await r.text()).slice(0,250)});}catch{}}});
await page.goto(APP+'/schedule',{waitUntil:'domcontentloaded',timeout:90000});
await page.waitForTimeout(9000);
await page.evaluate(()=>{const b=[...document.querySelectorAll('button')].find(e=>e.innerText.trim()==='Day'); b.click();});
await page.waitForTimeout(3500);
await page.evaluate(()=>{const d=[...document.querySelectorAll('.mini-calendar__day')].find(e=>e.innerText.trim()==='12'&&!e.className.includes('outside')); if(d)d.click();});
await page.waitForTimeout(4200);
await page.evaluate(()=>document.querySelectorAll('.schedule-block')[0].click());
await page.waitForTimeout(2200);
await page.evaluate(()=>{const d=document.querySelector('.q-dialog'); const x=[...d.querySelectorAll('button')].find(e=>/delete_outline/.test(e.innerText)); x.click();});
await page.waitForTimeout(2200);
// pick Entire series
await page.evaluate(()=>{const ds=[...document.querySelectorAll('.q-dialog')]; const d=ds[ds.length-1];
  const el=[...d.querySelectorAll('*')].filter(x=>x.children.length<=3&&/Entire series/.test(x.innerText||'')).pop(); if(el)el.click();});
await page.waitForTimeout(900);
await page.screenshot({path:E+'57-scope-selected.png'});
await page.evaluate(()=>{const ds=[...document.querySelectorAll('.q-dialog')]; const d=ds[ds.length-1]; const b=[...d.querySelectorAll('button')].find(e=>/^Delete$/.test(e.innerText.trim())); if(b)b.click();});
await page.waitForTimeout(1400);
F.toast=await page.evaluate(()=>document.querySelector('.undo-toast')?.innerText.trim().replace(/\n/g,' | ')||null);
await page.screenshot({path:E+'58-series-deleted-toast.png'});
console.log('TOAST',JSON.stringify(F.toast));
await page.waitForTimeout(2500);
F.remaining=await page.evaluate(()=>[...document.querySelectorAll('.schedule-block')].filter(e=>/Qispring/.test(e.innerText)).length);
console.log('remaining Qispring blocks',F.remaining);
await page.waitForTimeout(5000);
F.toastGone=await page.evaluate(()=>!document.querySelector('.undo-toast'));
console.log('toast gone by ~9s:',F.toastGone);
fs.writeFileSync('/tmp/sviu/f-seriesdel.json',JSON.stringify(F,null,1));
console.log('REQS',JSON.stringify(F.reqs,null,1));
await browser.close();
