out.after=await labor(s,W.wid); out.api=await apiTasks(s,W.wid); await shot(s,'ev/m6-2-wo-after-reload.png');
fs.writeFileSync('ev/m6.json',JSON.stringify(out,null,1)); console.log(J(out,3000)); await s.close();
