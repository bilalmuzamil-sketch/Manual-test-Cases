#!/usr/bin/env python3
"""Writes TECHNICIAN-TOGGLE-SETUP-FILE.md: the one setup file for Claude sessions (Rule 117 ninth amendment). It holds the accounts and
roles, the recipes that build each kind of record, every case's records with their ZZAUTOTEST names, traceability and open questions.
A manual tester never needs it: each case's own preconditions say what must exist. No secrets: credentials live only in /tmp."""
import sys, os, re, json, glob, importlib
D = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, D)
import tt_lib as L
from po_questions import QUESTIONS
_ORDER = ["cases_s1", "cases_s2", "cases_s3", "cases_s4", "cases_api", "cases_s6", "cases_inv"]
_MODS = sorted(os.path.basename(f)[:-3] for f in glob.glob(f"{D}/cases_*.py"))
for m in [x for x in _ORDER if x in _MODS] + [x for x in _MODS if x not in _ORDER]: importlib.import_module(m)
SECS = json.load(open(f"{L.P}/sections.json"))["sections"]
LAB = re.compile(r"\b(staff member|work order|line|location|role|part sale|department) ([A-Z]|\d)\b", re.I)

def names(c):
    out = {}
    for x in c["pre"] + c["steps"]:
        for m in LAB.finditer(x):
            kind, tag = m.group(1).lower(), m.group(2)
            lab = f"{kind} {tag}"
            if lab in out: continue
            if kind == "staff member": out[lab] = f'first name "ZZAUTOTEST", last name "{c["key"]} {tag}", email zzautotest+{c["key"].lower()}-{tag.lower()}@shopview.test'
            elif kind == "role": out[lab] = f'role name "ZZAUTOTEST {c["key"]} Role {tag}"'
            elif kind == "location":
                out[lab] = ("the second location of the test organization (record its name in the run notes)" if tag == "B" and "production" not in " ".join(c["pre"])
                            else f'location name "ZZAUTOTEST {c["key"]} Location {tag}"' if tag == "C" else "the test location")
            elif kind == "work order": out[lab] = f'customer "ZZAUTOTEST {c["key"]} Customer", asset "ZZAUTOTEST {c["key"]} Asset {tag}"; record the work order number the app assigns'
            elif kind == "line": out[lab] = f'line description "ZZAUTOTEST {c["key"]} line {tag}"'
            elif kind == "part sale": out[lab] = f'part sale for customer "ZZAUTOTEST {c["key"]} Customer"; record its number'
            elif kind == "department": out[lab] = f'department "ZZAUTOTEST {c["key"]} Department {tag}"'
    return out

R = []
w = R.append
w("# Technician Toggle — setup file for Claude sessions")
w("")
w("Generated by `authoring/render_setup.py` from the case library (2 Nov 2026). **For Claude sessions only: a manual tester never needs "
  "this file** (each case's own preconditions say what must exist). Expected results come only from PRD v17 (Confluence 977371146, "
  "version 17, 2 Nov 2026, Chris Ward). No secrets are kept here: cookies, passwords, API keys and OTP codes live only in `/tmp` "
  "(`chmod 600`) and are re-supplied per environment.")
w("")
w("## 1. Environments and accounts")
w("")
w("| What | Value |")
w("|---|---|")
w("| Where the feature lands | Staging, `https://app.staging.shopview.com` (no QA branch is known for SV-11788 on 2 Nov 2026) |")
w("| Release-day cases (section Release day, and API-15) | Production test account, `https://app.shopview.com`, location **Trucks Hill 2**; the before state is set up and screenshotted shortly before the release reaches production (Credit terms precedent, QA lead 26 Oct 2026) |")
w("| Sign-in for most cases | An Admin at the test location (Admin holds 'Settings → App Settings', the permission for Staff) |")
w("| Second location (location B) | The test organization's second location; record which one in the run notes |")
w("| Public API | A Public API key for the test organization (kept in `/tmp`), the Public API documentation for staff, and a request tool |")
w("| Built-in roles the PRD names | Office User, Time Clock User, Technician, Foreman, Parts Technician, Parts Manager (plus Service Advisor used as an ordinary role) |")
w("| Naming | Every record a case creates is named `ZZAUTOTEST <case key> ...` (section 4) and is removed after the run |")
w("")
w("## 2. Recipes (how to build each kind of record)")
w("")
REC = [
 ("New staff member", "Settings → Staff → New Staff Member: first name, last name, email, Role, location enrollment, Billable, then the toggle row "
  "below Billable (Time Clock, Sales Representative, Technician) → Save & Close. A staff member who must sign in also needs a password set "
  "(record it in `/tmp` only). API alternative (playbook §ROLES / STAFF / ADMIN): `POST /api/iam/create`."),
 ("Technician on or off on an existing staff member", "Edit Staff Member → Technician → Save & Close. Turning it off for someone with open work "
  "shows Turn Off Technician; click Save there. Editing a staff record logs that user out today (playbook: \"EDITING A STAFF RECORD KILLS THAT "
  "USER'S SESSION\"), except a Technician-only change (S1-R8): finish all record changes before signing in as that user."),
 ("Custom role from a template", "Settings → Roles & Permissions → Create custom role → Choose a template (Technician, Foreman, Office User or Time "
  "Clock User) → Apply → Role name `ZZAUTOTEST <key> Role A` → Create. 'Settings → App Settings' off for S1-34."),
 ("Service work order in a status", "Work Orders → New Work Order (customer + asset) gives Estimate; add a line (New Line) and approve it to reach "
  "Approved; start work for In Progress; move to Ready for Review; complete for Complete; invoice for Invoiced; take payment for Paid; decline "
  "the work order for Declined, or decline a single line for a declined line. Playbook: create a fresh work order (existing ones can bounce)."),
 ("Lead", "On the work order, Lead Technician dropdown → pick the person while they are still a technician."),
 ("Labor entry on a line", "Add Labor on the line, technician = the person (no time needed unless the case says so)."),
 ("Add Technician on a line", "New Line or Edit Line → Add Technician → pick the person (no labor)."),
 ("Line's own technician", "The technician set on the line itself, without labor and without Add Technician. **Confirm on the build how the "
  "screen sets it** (the PRD names it; the v9 tech plan maps it to the line's own technician field); record the click path here once proven."),
 ("On a line through a schedule shift", "Schedule → create a shift for the person on that line (the playbook notes the grid is click-to-create, so this is done by hand)."),
 ("Time recorded on a line", "Sign in as the person → open the work order → Start on an approved line → Stop. For a time entry on a given past date, "
  "a time sheet editor adds a manual entry for the person on the work order's Time Sheets tab."),
 ("Former technician (on work, no longer a technician)", "Make the person a technician, give them the lead or line, then switch Technician off "
  "and click Save in Turn Off Technician. Nothing is unassigned (S2-R5)."),
 ("Pinned Board View column", "Board View → the person's column → pin it (while they are still a technician) → then switch their Technician off."),
 ("Location C (no technicians)", "Create a location `ZZAUTOTEST <key> Location C` in the organization; enroll no technician there (any staff "
  "enrolled there has Technician off)."),
 ("Computer clock for the pill and notice", "Set the operating system clock (not the app). The PRD reads the end date from the viewer's own clock "
  "(S1-R2). Until the release is scheduled the build carries 31 Dec 2026, 07:00 UTC (SV-12008)."),
 ("Public API requests", "Read: `GET /api/v1/staff`, `GET /api/v1/staff/<id>`, `GET /api/v1/locations/<id>/staff`. Update: `PATCH /api/v1/staff/<id>` "
  "(`technician` is ignored, S5-N1). Names from the v9 tech plan's API table; confirm against the Public API documentation. A role change and a "
  "work order lead change through the Public API are not named in any saved source (API-12, API-13 held)."),
]
for t, r in REC: w(f"- **{t}:** {r}")
w("")
w("## 3. Questions (all 8 answered, 2 Nov 2026) and held cases")
w("")
for i, (slug, q, basis, opts, holds) in enumerate(QUESTIONS, 1):
    keys = [c["key"] for c in L.CASES if c["marker"] == L.PO_HOLD(i)]
    w(f"- **Question {i}** ({slug}): {q} **Answered by Chris Ward, 2 Nov 2026:** {L.ANS[i]} Held now: {', '.join(keys) or 'none'}.")
w("- Other held cases and why: " + "; ".join(f"{c['key']} ({c['marker'][len('AUTOMATION: HOLD - '):]})" for c in L.CASES
                                             if c["held"] and "waiting on the PO" not in c["marker"] and c["marker"] != L.PRE_REL) + ".")
w(f"- Release-day cases held with the production marker: {', '.join(c['key'] for c in L.CASES if c['marker'] == L.PRE_REL)}.")
w("")
w("## 4. Every case: its records and their ZZAUTOTEST names")
w("")
for c in L.CASES:
    sec = SECS[c["sec"]]["name"]
    w(f"### {c['key']} — {c['title']}")
    w(f"Section: {sec} · stories {L.refs_of(c)} · PRD items {', '.join(sorted(L.codes_of(c)))} · {c['marker']}")
    w("")
    for p in c["pre"]: w(f"- {p}")
    n = names(c)
    if n:
        w("")
        w("Names to use: " + "; ".join(f"**{k}** = {v}" for k, v in n.items()) + ".")
    w("")
open(f"{L.P}/TECHNICIAN-TOGGLE-SETUP-FILE.md", "w").write("\n".join(R) + "\n")
print("TECHNICIAN-TOGGLE-SETUP-FILE.md", len(R), "lines")
