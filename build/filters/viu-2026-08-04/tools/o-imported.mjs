import * as H from './h.mjs';
import fs from 'fs';
const {browser,page,netlog}=await H.open();
const R={}; const S=n=>{fs.writeFileSync('/tmp/fviu/o-imported.json',JSON.stringify(R,null,1));console.log('..'+n);};
const T=async(k,fn)=>{try{R[k]=await fn();}catch(e){R[k]={ERROR:e.message.slice(0,200)};}S(k);};
await H.resetFilters(page);
await T('open',()=>H.openChip(page,'Status'));
let n=H.listCalls(netlog).length;
await T('tickImported',async()=>{await page.locator('[data-test-id="filter_option_status_imported"]').first().click({timeout:20000});await page.waitForTimeout(4500);
  return {calls:H.listCalls(netlog).slice(n),url:page.url(),chips:await H.chips(page),rows:await H.rows(page),panelOpen:await H.panelOpen(page)};});
await H.shot(page,'imp-01');
for(const c of ['Customer','Lead Technician','Service Advisor','Asset on Site']) await T('state_'+c.replace(/ /g,'_'),()=>H.chipEnabled(page,c));
await T('statusChipState',()=>H.chipEnabled(page,'Status'));
await T('tryOpenCustomer',async()=>{try{await page.locator(H.chipSel('Customer')).first().click({timeout:6000});await page.waitForTimeout(1500);
  return {clicked:true,panelOpen:await H.panelOpen(page)};}catch(e){return {clicked:false,err:e.message.slice(0,120)};}});
await T('reopenStatusWithImported',async()=>{const o=await H.openChip(page,'Status');return {o,panel:await H.panel(page)};});
await T('addPaidWhileImported',async()=>{try{await page.locator('[data-test-id="filter_option_status_paid"]').first().click({timeout:8000});await page.waitForTimeout(4000);
  return {clicked:true,url:page.url(),chips:await H.chips(page),rows:await H.rows(page)};}catch(e){return {clicked:false,err:e.message.slice(0,150)};}});
await H.shot(page,'imp-02');
await T('clearFiltersWithImported',async()=>{const ok=await H.resetFilters(page);return {ok,url:page.url(),chips:await H.chips(page)};});
await browser.close();
console.log('DONE');
