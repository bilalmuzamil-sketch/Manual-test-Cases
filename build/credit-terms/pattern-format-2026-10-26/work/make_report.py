#!/usr/bin/env python3
"""Pass report for the QA lead's case pattern (Rule 117 fourteenth amendment, 26 Oct 2026). Compares before/proposals.json (the rendered
fields before the pass) with authoring/proposals.json (after build.py). Writes ../PASS-REPORT.md and prints a summary.
python3 make_report.py   (run authoring/build.py first)"""
import os, sys, re, json, html, csv
W = os.path.dirname(os.path.abspath(__file__)); F = os.path.dirname(W); P = os.path.dirname(F); A = f"{P}/authoring"
sys.path.insert(0, A); os.chdir(A)
import ct_lib as L, build_mods, pattern as PAT
BEFORE = json.load(open(f"{F}/before/proposals.json")); AFTER = json.load(open(f"{A}/proposals.json"))
IDS = {r["key"]: (r["case_id"], r["link"]) for r in csv.DictReader(open(f"{P}/testrail-id-map.csv"))}
CASE = {c["key"]: c for c in L.CASES}
U = lambda s: html.unescape(s)
def lis(h): return [U(x) for x in re.findall(r"<li>(.*?)</li>", h, re.S)]
def block(h, start, end=None):
    i = h.index(start); j = h.index(end, i) if end else len(h)
    return h[i:j]
def quotes_of(h): return block(h, "<p><strong>Exact quotes from the source", "<p></p><p><strong>References from Design")
def design_of(h): return block(h, "<p></p><p><strong>References from Design", "<p>AUTOMATION: ")
def auto_of(h): return h[h.rindex("<p>AUTOMATION: "):]
def old_parts(f):
    pre = f["custom_preconds"].split("<p><strong>Preconditions</strong></p><ul>", 1)[1]
    items = [U(x) for x in re.findall(r"<li>(.*?)</li>", pre, re.S)]
    scen = items[0][len("Scenario: "):] if items and items[0].startswith("Scenario: ") else ""
    state, ex = [], []
    for x in items[1:]:
        a, _, b = x.partition("<br>"); state.append(a); ex.append(b)
    exp = f["custom_expected"]
    res = lis(exp.split("</ul>", 1)[0])
    return scen, state, ex, lis(f["custom_steps"]), res
def new_parts(f):
    pre = lis(f["custom_preconds"]); exp = f["custom_expected"]
    head = exp.split("<p></p>", 1)[0]
    res = []
    for n, body in re.findall(r"<p>Step (\d+):</p><ul>(.*?)</ul>", head, re.S): res.append(lis(body))
    return pre, lis(f["custom_steps"]), res

# ---- facts: amounts, dates, quoted labels, term names, numbers (placeholders mapped to the plain names this case uses)
MON = r"(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)"
def facts(text):
    t = text
    out = set(re.findall(r"\$[\d,]+(?:\.\d+)?", t))
    out |= set(re.findall(MON + r" \d{1,2}(?:, \d{4})?", t))
    out |= {q for q in re.findall(r'"([^"]+)"', t) if len(q) > 1}
    out |= set(re.findall(r"\b(?:Net \d+|COD|Due on Receipt|Credit Hold)\b", t))
    out |= set(re.findall(r"(?<![\w-])\d+(?:[.,]\d+)?(?![\w-])", t))
    return out
def norm(s): return re.sub(r"\s+", " ", s.replace("“", '"').replace("”", '"'))
BLOCKED_OLD = L.BLOCKED

rows, lost_all, scen_only, ident = [], {}, {}, {"quotes": 0, "design": 0, "auto": 0, "title": 0, "note_changed": []}
for k, b in BEFORE.items():
    a = AFTER[k]; c = CASE[k]; names = PAT.names_for(c)
    hb, ha = b["fields"]["custom_expected"], a["fields"]["custom_expected"]
    ident["quotes"] += quotes_of(hb) == quotes_of(ha); ident["design"] += design_of(hb) == design_of(ha); ident["auto"] += auto_of(hb) == auto_of(ha)
    ident["title"] += b["title"] == a["title"]
    _ob = U(re.sub(r"<[^>]+>", "", hb.split("</ul>", 1)[1].split("<p><strong>Exact quotes")[0])).strip()
    _na = U(re.sub(r"<[^>]+>", "", ha.split("<p></p>", 1)[1].split("<p><strong>Exact quotes")[0])).strip()
    if _ob != _na: ident["note_changed"].append((k, _ob, _na))
    scen, st, ex, osteps, ores = old_parts(b["fields"]); npre, nsteps, nres = new_parts(a["fields"])
    old_text = " ".join([PAT.sub(x, names) for x in st if x != BLOCKED_OLD] + [PAT.sub(x, names) for x in osteps] + [PAT.sub(x, names) for x in ores])
    old_text = re.sub(r"\bStep \d+: ", "", old_text)
    new_text = norm(" ".join([a["title"]] + npre + nsteps + [x for r in nres for x in r] + [PAT.sub(c["note"], names)]))
    lost = sorted(f for f in facts(norm(old_text)) if f not in new_text)
    if lost: lost_all[k] = lost
    so = sorted(f for f in facts(scen) if f not in new_text and f not in norm(old_text))
    if so: scen_only[k] = so
    rows.append((k, b, a, scen, st, ex, osteps, ores, npre, nsteps, nres))

N = len(BEFORE)
R = []; W_ = R.append
W_("# Credit terms: every case in the QA lead's pattern (26 Oct 2026)"); W_("")
W_('QA lead, 26 Oct 2026: *"See this pattern and format the test case :"* and, asked whether it is permanent, **"Yes, permanent, all suites"** '
   "(Rule 117, fourteenth amendment; lessons L-06 to L-10). Draft only: nothing written to TestRail, Jira, Slack or Google; nothing committed.")
W_(""); W_("Generated by `pattern-format-2026-10-26/work/make_report.py` from `before/proposals.json` (the rendered fields before this pass) "
        "and `authoring/proposals.json` (after `authoring/build.py`).")
W_(""); W_("## 1. Checks")
W_(f"- Cases reformatted: **{N} of {N}** (every case's Preconditions, Steps and Expected Result are in the pattern; titles unchanged, they already met it).")
W_(f"- Exact quotes block with its From lines, byte-identical to before: **{ident['quotes']} of {N}**.")
W_(f"- References from Design block, byte-identical: **{ident['design']} of {N}**.")
W_(f"- AUTOMATION line, byte-identical and last: **{ident['auto']} of {N}**.")
W_(f"- Title unchanged: **{ident['title']} of {N}**.")
W_(f"- Notes below the blank line (held / design-difference / other): unchanged except where they named a placeholder or another case (relevance and independence pass, RELEVANCE-PASS.md): "
   + (", ".join(f"{k} ({o!r} -> {n!r})" for k, o, n in ident["note_changed"]) or "none") + ".")
W_(f"- No fact lost (every amount, date, quoted label, term name and number of the old preconditions, steps and results, with placeholders "
   f"read as the plain names, is in the new title, preconditions, steps, results or note; \"For example\" lines excluded): "
   + ("**YES, all cases**." if not lost_all else f"**YES** for {N - len(lost_all)} cases; {len(lost_all)} case(s) explained one by one in section 4 ({', '.join(lost_all)})."))
W_(f"- Facts only in the removed Scenario line (not in the old or new preconditions, steps or results): "
   + ("none." if not scen_only else "; ".join(f"{k}: {', '.join(v)}" for k, v in scen_only.items()) + "."))
W_("- `authoring/build.py`: PROBLEM lines 0 (see section 2 for the gates).")
W_(""); W_("## 2. The pattern and its gate")
W_("- Preconditions: a \"Preconditions\" heading and plain bullets only, in setup order (Sign in → records and their state → browser → design "
   "pictures → starting screen), the Blocked line last: \"" + PAT.BLOCKED_P + "\". No Scenario line, no {placeholder}, no \"For example\", no "
   "setup-file link, no who-to-ask or generic line, no ZZAUTOTEST example name.")
W_("- Records keep one plain name used the same way in preconditions, steps and results: term A, customer B, vendor A, work order 1, invoice A, "
   "user B, role A; one location is \"the test location\", two are location A and location B; a number written down before the test is number A; "
   "a date worked out from today is date A; the signed-in user's own name is \"your user name\".")
W_("- A value the result depends on became a plain fact (it was the example): " + "; ".join(f"{k}: " + ", ".join(f"{{{p}}} = {v}" for p, v in d.items()) for k, d in PAT.VALUES.items()) + ".")
W_("- Steps: the same actions, with the plain names (\"Type the name of term A in Name.\").")
W_("- Expected Result: \"Step N:\" then one bullet per sentence of the old result (a \"; \" outside quotes and brackets also splits), "
   "then one blank paragraph, then the note (if any), the exact quotes with their From lines, References from Design and the AUTOMATION line, unchanged.")
W_("- `authoring/build.py` gate (replaces the Scenario gate; every other gate kept): the shape above, checked on the rendered HTML; the tail "
   "from \"Exact quotes from the source\" to the AUTOMATION line equal to `before/proposals.json`; every User Feedback Summary message still "
   "word for word in the pattern steps and results.")
W_(""); W_("### Hand-written forms (the rules could not phrase these plainly; meaning kept)")
for (k, a), v in PAT.PRE_OVR.items(): W_(f"- {k} precondition: \"{a}\" → " + " / ".join(f"\"{x}\"" for x in v))
for (k, n), v in PAT.RES_OVR.items(): W_(f"- {k} Step {n} result → " + " / ".join(f"\"{x}\"" for x in v))
W_("")
W_("## 3. Old and new, every case")
W_("Old: the Scenario line, the preconditions (with their \"For example\" lines), steps and results before this pass. New: as they will read in TestRail. "
   "The quotes, From lines, References from Design and AUTOMATION line are not repeated (identical, section 1).")
for k, b, a, scen, st, ex, osteps, ores, npre, nsteps, nres in rows:
    cid, link = IDS.get(k, ("", ""))
    W_(""); W_(f"### {k} · C{cid} · {link}")
    W_(f"- Title (old = new): {a['title']}" if b["title"] == a["title"] else f"- Title: old \"{b['title']}\" → new \"{a['title']}\"")
    W_("- **Old preconditions**")
    if scen: W_(f"  - Scenario: {scen}")
    for x, y in zip(st, ex): W_(f"  - {x}" + (f" _{y}_" if y else ""))
    W_("- **New preconditions**")
    for x in npre: W_(f"  - {x}")
    W_("- **Old steps** / **new steps**")
    for i, (x, y) in enumerate(zip(osteps, nsteps), 1): W_(f"  {i}. {x}" if x == y else f"  {i}. {x}  →  {y}")
    W_("- **Old results**")
    for x in ores: W_(f"  - {x}")
    W_("- **New Expected Result**")
    for i, r in enumerate(nres, 1):
        W_(f"  - Step {i}:")
        for x in r: W_(f"    - {x}")
EXPLAIN = {
 **{k: "dropped in the relevance pass with a record no step or result uses (the three customers' credit limits and A to Z order; see RELEVANCE-PASS.md)"
    for k in ("S4-04", "S4-16", "S4-20", "S4-34")},
 "S4-08": "dropped in the relevance pass with a record no step or result uses (the third customer's $0.00 credit limit; see RELEVANCE-PASS.md)",
 "D-33": "same facts, new words (hand-written result, section 2): the on-screen labels joined the work order number and term name to "
         "placeholders (\"INV-{Work-order-1}\", \"Work Order {Work-order-1}\", \"Terms {Term-A}\"); they now read \"INV-\" followed by work order 1's "
         "number, \"Work Order\" with work order 1's number, and \"Terms\" with term A's name.",
}
SCEN_EXPLAIN = {
 "S4-11": "the removed Scenario line said the customer moves to Net 30; the case's own steps and results move it to Due on Receipt (the default) and still do. The Scenario line was wrong; nothing in the case changes.",
 "S5-25": "the Scenario's \"$500\" is the step's \"credit limit of 500\", still in the step.",
 "S9-04": "the Scenario's \"$600\" is the precondition's \"$600.00\", still in it.",
}
W_(""); W_("## 4. No-fact-lost exceptions")
if not lost_all: W_("None: every fact is still in the case.")
for k, v in lost_all.items(): W_(f"- {k}: " + ", ".join(repr(x) for x in v) + (" — " + EXPLAIN[k] if k in EXPLAIN else " — NOT EXPLAINED"))
W_(""); W_("Facts that were only in the removed Scenario line:")
for k, v in scen_only.items(): W_(f"- {k}: " + ", ".join(repr(x) for x in v) + (" — " + SCEN_EXPLAIN[k] if k in SCEN_EXPLAIN else " — NOT EXPLAINED"))
W_(""); W_("## 5. Cases that could not be reformatted without losing meaning")
W_("None. Every case is in the pattern; the few bullets the rules could not phrase plainly were written by hand (section 2) with the same meaning.")
open(f"{F}/PASS-REPORT.md", "w").write("\n".join(R) + "\n")
print("cases", N, "| quotes identical", ident["quotes"], "| design identical", ident["design"], "| automation identical", ident["auto"],
      "| titles same", ident["title"], "| notes changed", [k for k, _, _ in ident["note_changed"]])
print("fact-lost cases", len(lost_all)); [print("  LOST", k, v) for k, v in list(lost_all.items())[:60]]
print("scenario-only facts", scen_only)
