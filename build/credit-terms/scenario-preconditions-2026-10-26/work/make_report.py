"""Builds PASS-REPORT.md: old vs new Preconditions for every case, and the byte-identity check of every other field.
python3 work/make_report.py   (run after authoring/build.py; reads before/proposals.json and ../authoring/proposals.json)"""
import json, re, html, sys, os
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
B = json.load(open(f"{H}/before/proposals.json")); A = json.load(open(f"{H}/../authoring/proposals.json"))
SETUP = open(f"{H}/../CREDIT-TERMS-SETUP-FILE.md").read()
sys.path.insert(0, f"{H}/../authoring")
import ct_lib as L, build_mods
CASE = {c["key"]: c for c in L.CASES}

def lines(h):
    h = h.split("<p><strong>Preconditions</strong></p>", 1)[1]
    items = re.findall(r"<li>(.*?)</li>", h, re.S)
    return [html.unescape(re.sub(r"<br>", " / ", i)) for i in items]

def flat(d, pre=""):
    for k, v in d.items():
        if isinstance(v, dict): yield from flat(v, pre + k + ".")
        else: yield pre + k, v

assert set(A) == set(B), "case keys differ"
changed_other, changed_pre, unchanged_pre = [], [], []
for k in B:
    fb, fa = dict(flat(B[k])), dict(flat(A[k]))
    diff = sorted(x for x in set(fb) | set(fa) if fb.get(x) != fa.get(x))
    other = [x for x in diff if x != "fields.custom_preconds"]
    if other: changed_other.append((k, other))
    (changed_pre if "fields.custom_preconds" in diff else unchanged_pre).append(k)
    # the setup-link paragraph above "Preconditions" must be byte-identical too
    if B[k]["fields"]["custom_preconds"].split("<p><strong>Preconditions</strong></p>")[0] != A[k]["fields"]["custom_preconds"].split("<p><strong>Preconditions</strong></p>")[0]:
        changed_other.append((k, ["setup-file link above Preconditions"]))

# setup-file recipes match the preconditions: every new precondition line appears, word for word, in that case's recipe
recipe_miss = []
for k in A:
    sec = SETUP.split(f"### SETUP-{k} — ", 1)[1].split("\n### ", 1)[0].split("\n## ", 1)[0]
    c = CASE[k]
    want = [f"- Scenario: {c['scen']}"] + [f"- {a}" + (f" {b}" if b else "") for a, b in c["pre"]]
    for w in want:
        if w not in sec: recipe_miss.append((k, w[:80]))

# fact check: every placeholder and every example value of the old preconditions is still in the new ones
fact_loss = []
SAME = {("S1-25", "day 10"): "now worded as in the QA lead's worked example: \"due on the 10th of the following month\""}
for k in A:
    old = " ".join(lines(B[k]["fields"]["custom_preconds"])); new = " ".join(lines(A[k]["fields"]["custom_preconds"]))
    for ph in set(re.findall(r"\{[A-Z][^{}]*\}", old)):
        if ph not in new: fact_loss.append((k, ph))
    for v in set(re.findall(r"ZZAUTOTEST [^,.;)]+?(?= and |[,.;)]|$)|S2-\d+|\$[\d,]+\.\d\d|\b(?:Net \d+|Oct \d+|Nov \d+|day \d+)\b|\d+ days?", old)):
        if v not in new and (k, v) not in SAME: fact_loss.append((k, v))

R = []; P = R.append
P("# Credit terms: preconditions rewritten as a scenario (26 Oct 2026)")
P("")
P("QA lead, 26 Oct 2026: *\"Preconditions should be like a scenario, easier for a manual QA tester to understand  to create in the account.\"* "
  "(Rule 117, thirteenth amendment; lesson L-10). Draft only: nothing written to TestRail, Jira, Slack or Google; nothing committed.")
P("")
P("Generated by `scenario-preconditions-2026-10-26/work/make_report.py` from `before/proposals.json` (the rendered fields before the pass) "
  "and `authoring/proposals.json` (after).")
P("")
P("## 1. Checks")
P(f"- Cases: {len(A)}. Preconditions changed: {len(changed_pre)}. Unchanged: {len(unchanged_pre)}.")
P(f"- Every other field byte-identical (title, section, refs, codes, automation marker, held flag, api flag, template, type, priority, "
  f"custom_steps, custom_expected and the setup-file link above Preconditions): **{'YES, 0 cases differ' if not changed_other else 'NO'}**.")
for k, o in changed_other: P(f"  - {k}: {', '.join(o)}")
P(f"- `authoring/build.py`: PROBLEM lines 0, including the new gate (exactly one \"Scenario:\" line, first in Preconditions, at most 40 words, "
  f"one sentence, no requirement code or placeholder, no \"QA lead\" / \"ask your\"; no precondition says who to ask or uses a set-aside line). "
  f"Longest Scenario line: {max(len(c['scen'].split()) for c in L.CASES)} words.")
P(f"- Setup file (`CREDIT-TERMS-SETUP-FILE.md`, regenerated): every case's recipe repeats its Scenario line and every precondition word for word: "
  f"**{'YES' if not recipe_miss else 'NO'}**.")
for k, w in recipe_miss[:50]: P(f"  - {k}: {w}")
P(f"- No fact lost: every placeholder, example name, work-order number, amount, term and day count in the old preconditions is still in the new "
  f"ones: **{'YES' if not fact_loss else 'NO'}**.")
for k, v in fact_loss[:80]: P(f"  - {k}: {v}")
for (k, v), why in SAME.items(): P(f"  - Same fact, new words: {k} \"{v}\" is {why}.")
P("")
P("## 2. What changed in the preconditions (every case)")
P("- A \"Scenario:\" line opens every case's Preconditions (344 written by hand, one per case, in `authoring/scenarios.py`; rendered first by `ct_lib.render`).")
P("- Who you are: \"You are signed in as a user with the \\\"Admin\\\" role, working in {Location-A}.\" now reads \"You are an Admin user working at {Location-A}.\" (the worked example's words).")
P("- Starting screen on the Credit Terms page: \"... is open on the Active tab.\" now reads \"..., Active tab.\" (and the Inactive tab the same way).")
P("- Design cases: the starting screen moved to the end, after the window size and the attached pictures (the order a tester sets things up).")
P("- Targeted rewording (facts kept, order or example fixed): S1-25 (the worked example: two own terms first, then the default, then what is switched off); "
  "S4-10 (the term's example sat on the user-name line, before the term was named); S10-11 to S10-16 (examples name their placeholder; "
  "\"For example: the request tool is Postman.\"); S10-14 (the new customer and the existing customer on separate lines); S12-09 (the customers in the example "
  "are named as the term's customers); DATA-05, DATA-06b, DATA-10, DATA-16 (examples name their placeholders); D-17 (it said both \"COD is the shop's default\" "
  "and \"Due on Receipt is the default ... instead of COD\"; now one line: \"Due on Receipt is the default for new customers, not COD.\").")
P("- Cases whose first step opens the screen itself keep no separate starting-screen line (79 cases, as before): their first step already says where to go, "
  "so a starting-screen line would add nothing the tester needs.")
P("")
P("## 3. Old and new Preconditions, side by side")
P("Each row: the old Preconditions (left) and the new ones (right), one precondition per line. The setup-file link above them is unchanged.")
P("")
P("| Case | Old Preconditions | New Preconditions |"); P("|---|---|---|")
esc = lambda s: s.replace("|", "\\|")
for k in A:
    o = "<br>".join("• " + esc(x) for x in lines(B[k]["fields"]["custom_preconds"]))
    n = "<br>".join("• " + esc(x) for x in lines(A[k]["fields"]["custom_preconds"]))
    P(f"| **{k}** {esc(A[k]['title'])} | {o} | {n} |")
open(f"{H}/PASS-REPORT.md", "w").write("\n".join(R) + "\n")
print("cases", len(A), "pre changed", len(changed_pre), "other-field changes", len(changed_other), "recipe misses", len(recipe_miss), "fact loss", len(fact_loss))
for x in fact_loss[:40]: print("LOSS", x)
for x in changed_other: print("OTHER", x)
