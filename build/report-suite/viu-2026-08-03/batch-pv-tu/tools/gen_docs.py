B = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
rows = list(csv.DictReader(open(os.path.join(B, 'verdicts.csv'))))
tally = Counter(r['verdict'] for r in rows)
per = {}
for r in rows: per.setdefault(r['report'], Counter())[r['verdict']] += 1
L = []
w = L.append
w('# Parts Velocity + Technician Utilization — LIVE VIU VERDICTS (2026-08-03/04)')
w('')
w('**Scope: 131 cases — Parts Velocity 71 + Technician Utilization 60.** Every case carries ONE')
w('definite verdict. There are **no "partly observed" rows**.')
w('')
w('## SOURCE-CURRENCY BLOCK (Standing Rule 31)')
w('')
w('| Source | Identifier | Version / last-updated | Checked | Verdict |')
w('|---|---|---|---|---|')
w('| PV spec | Confluence pageId 620888066 | **v4**, last modified 2026-07-29 | 2026-08-03 (live capture reused) | **CURRENT** |')
w('| TU spec | Confluence pageId 641400833 | **v5**, last modified 2026-07-29 | 2026-08-03 (mirror proven same-version) | **CURRENT** |')
w('| Epic | SV-8582 | not re-read this run | 2026-07-31 (6 stories reopened) | **PARTIAL** — a Tier-2 full re-read was not authorised for this batch (Rule 37) |')
w('| Designs | none exist for the Report Suite | n/a | — | **N/A** (spec-only project, no Rule-35 queue) |')
w('| Tech plan | build/report-suite/tech-plan-2026-07-29 | 2026-07-29, not re-fetched | — | **PARTIAL** |')
w('| PO answers | Chris Ward, through 2026-08-01 | — | — | **CURRENT** |')
w('| **Live build** | `sv8582.qa.shopview.com` | **v3.4.1-0ed4433** — `last-modified Mon, 03 Aug 2026 13:40:38 GMT`, `etag 02091e9dc11f187d7739b4efa166ea21` | **re-captured at the START and at the END of this run — IDENTICAL, the build did not change mid-run** | **PARTIAL — DECLARED NOT FINAL** |')
w('')
w('**Because the branch is NOT FINAL, every verdict below is PROVISIONAL (Standing Rule 49).**')
w('All 131 rows are queued in `RECHECK-ROWS.md` with the build marker. **No suite may be called')
w('VIU-complete while that queue is open.**')
w('')
w('## TALLY')
w('')
w('| Verdict | Cases | Meaning |')
w('|---|---:|---|')
w('| **VIU-Observed-PASS** | **%d** | The case\'s assertion was driven live and the build matched. |' % tally['VIU-Observed-PASS'])
w('| **DEVIATION** | **%d** | Driven live; the build and the spec/ruling disagree. Each row quotes the spec verbatim and says whether I read it as a defect or as not-built-yet on an unfinished branch. |' % tally['DEVIATION'])
w('| **NOT-BUILT** | **%d** | Nothing in scope was absent from the build. |' % tally.get('NOT-BUILT', 0))
w('| **EXTERNAL-DEPENDENCY** | **%d** | Fully characterised below; not a seeding gap. |' % tally['EXTERNAL-DEPENDENCY'])
w('| **PARTLY OBSERVED** | **0** | Not an accepted verdict in this batch. |')
w('| **TOTAL** | **%d** | |' % len(rows))
w('')
w('Per report:')
w('')
w('| Report | Total | PASS | DEVIATION | EXTERNAL-DEP |')
w('|---|---:|---:|---:|---:|')
for k in ('Parts Velocity', 'Technician Utilization'):
    c = per[k]; w('| %s | %d | %d | %d | %d |' % (k, sum(c.values()), c['VIU-Observed-PASS'], c['DEVIATION'], c['EXTERNAL-DEPENDENCY']))
w('')
w('## SEVEN-FIELD SWEEP (every case, every field)')
w('')
f_counts = {}
for fld in ('field_title','field_preconditions','field_steps','field_expected','field_references','field_section','field_notes'):
    f_counts[fld] = Counter('EDIT' if r[fld].startswith('EDIT') else 'OK' for r in rows)
w('| Field | OK | EDIT | What was checked |')
w('|---|---:|---:|---|')
w('| Title | %d | %d | Accuracy against what the build does, length (all 131 are inside 80 characters), and agreement with the case\'s own expected result. |' % (f_counts['field_title']['OK'], f_counts['field_title']['EDIT']))
