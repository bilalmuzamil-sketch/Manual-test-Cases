w('| Steps | %d | %d | Executable in order using the build\'s real control names (verified handles: `input_report_search` "Search parts", `btn_dropdown_pv_export` / `btn_dropdown_tu_export` aria "Export report", `button_column_selection` aria/tooltip "Column Selection", `span.date-range-label`, `button_tu_expand_all`). No non-executable step was found in either report. |' % (f_counts['field_steps']['OK'], f_counts['field_steps']['EDIT']))
