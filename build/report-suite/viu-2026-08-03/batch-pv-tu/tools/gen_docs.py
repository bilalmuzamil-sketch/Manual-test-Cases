w('| References | %d | %d | **Checked on every one of the 131 cases.** All 131 carry a Jira ticket AND a spec anchor, every anchor still exists in the current PV v4 / TU v5 spec bodies, and every anchor governs the assertion the case makes. **No reference change is needed anywhere in this batch.** The single documented exception is PV-PREC-02, whose refs state in as many words that no report spec covers QuickBooks and cite the tech plan instead. |' % (f_counts['field_references']['OK'], f_counts['field_references']['EDIT']))
w('| Section | %d | %d | The 6 API-content cases (PV-API-01..04, PV-PREC-02, TU-API-01/02) are already in `PV — API` / `TU — API` sections; no UI-only case contains API content. **No section move needed.** |' % (f_counts['field_section']['OK'], f_counts['field_section']['EDIT']))
w('| Notes | %d | %d | **All 131 need the same addition** — the Rule-49 non-final-build marker (metadata layer, never tester-facing). No FE-hidden / BE-allowed situation arises in either report (the permission model is enforced on the back end with 403s), so no Rule-24 tester note is required. |' % (f_counts['field_notes']['OK'], f_counts['field_notes']['EDIT']))
w('')
w('## THE 4 EXTERNAL-DEPENDENCY ROWS — fully characterised')
w('')
for r in rows:
    if r['verdict'] != 'EXTERNAL-DEPENDENCY': continue
    w('### %s = [%s](%s) — %s' % (r['internal_id'], r['testrail_case_id'], r['testrail_link'], r['title']))
    w('')
    w(r['observed'])
    w('')
    w('*Evidence:* `%s` · *Unblocked by:* %s' % (r['evidence'], r['recheck_obligation']))
    w('')
w('## THE %d DEVIATIONS' % tally['DEVIATION'])
w('')
w('Each row quotes the spec verbatim (Standing Rule 25) and states my read.')
w('')
for r in rows:
    if r['verdict'] != 'DEVIATION': continue
    w('### %s = [%s](%s)' % (r['internal_id'], r['testrail_case_id'], r['testrail_link']))
    w('')
    w('**%s**' % r['title'])
    w('')
    w(r['observed'])
    w('')
    w('*Evidence:* `%s`' % r['evidence'])
    w('')
w('## FULL PER-CASE TABLE (all %d)' % len(rows))
w('')
w('The machine-readable table with all seven field verdicts per case is **`verdicts.csv`**.')
w('')
w('| Internal ID | C-id | Link | Verdict | Fields needing an edit | Evidence |')
w('|---|---|---|---|---|---|')
for r in rows:
    eds = [k.replace('field_', '') for k in ('field_title','field_preconditions','field_steps','field_expected','field_references','field_section','field_notes') if r[k].startswith('EDIT')]
    w('| %s | %s | [open](%s) | %s | %s | `%s` |' % (r['internal_id'], r['testrail_case_id'], r['testrail_link'], r['verdict'], ', '.join(eds), r['evidence'].split(';')[0].strip()))
w('')
w('## WHAT WAS SEEDED, AND THAT IT WAS CLEANED UP (Standing Rules 5 / 14)')
w('')
w('| Seeded | How | Removed |')
w('|---|---|---|')
w('| Clocked internal time for 3 technicians at BOTH locations, so the empty This-Month Technician Utilization view had rows, one technician had hours at two locations (the "Multiple" case), and one clock stayed OPEN | `POST /api/switch-user` to impersonate, then `POST /api/technician-tasks/department-clock-in {department_id}` (snake_case) → 201, `.../department-clock-out {task_id, description}` → 201, with `POST /api/iam/change-location` between locations | **Yes** — the open clock was closed (201) and all 4 records deleted with `DELETE /api/technician-tasks/{id}` → 204 each; the This-Month view is empty again |')
w('| Catalogue part + inventory part `ZZAUTOTEST-CORE-1` (5 on hand), then a $25 core attached to it, to settle the core-exclusion rule | `POST /api/parts-catalogue/add-catalogue-part` → 201, `POST /api/inventory/parts/create` (bins take `{id, quantity, isDefault}`) → 201, `POST /api/inventory/parts/change {core:true, core_charge:25}` → 201 | **Yes** — inventory part deleted (201), catalogue part removed (200), search returns nothing |')
w('| A one-location reports user, to settle the Location-filter visibility question | reassigned an existing Technician to Sales Representative + a single workplace, impersonated, observed, restored | **Yes** — restored to Technician / Lethbridge and re-read to confirm |')
w('| Nothing else. The labour-rate probes returned 201 but did **not** persist, so the labour configuration is byte-identical (the one default is still "CP RAIL FLEET RATE" at 145) | — | n/a |')
w('')
w('## HONEST LIMITS OF THIS BATCH')
w('')
w('1. **The branch is not final** — every verdict is provisional and queued.')
w('2. **Four assertions are environment-blocked** (the em-dash Est. Lost Labor family and QuickBooks) — characterised above, not hidden.')
w('3. **Eleven PASS rows carry a stated narrower limit** inside their `observed` text (for example: the 366-day cap was driven through the API rather than from the calendar UI; the return SOURCE records could not be cross-read because `/api/returns` 404s; no fractional Units Sold exists on this org; the PDF logo fallback could not be exercised because this organisation has an uploaded logo). Each of those limits is written on the row and carries its own re-check obligation — none of them is presented as full coverage.')
w('4. **The epic was not re-read** (Tier-2, Rule 37) and the tech plan was not re-fetched.')
w('5. Nothing was written to TestRail. Every proposed change is staged in `STAGED-CHANGES.md`.')
