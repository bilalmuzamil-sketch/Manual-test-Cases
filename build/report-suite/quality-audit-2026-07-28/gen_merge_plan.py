#!/usr/bin/env python3
"""Renders MERGE-PLAN.md from gen_verdicts.py's MERGES/CUTS/WEAK dicts + the id-map.
Analysis only — NO case files edited, NO TestRail writes."""
import csv, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_verdicts import MERGES, CUTS, WEAK, MERGE_REASON

IDMAP = '/tmp/rs-audit/testrail-id-map.csv'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'MERGE-PLAN.md')

idmap, titles = {}, {}
for row in csv.DictReader(open(IDMAP)):
    idmap[row['internal_id']] = row['testrail_case_id']
    titles[row['internal_id']] = row['title']

def ref(cid):
    c = idmap.get(cid, '')
    if not c:
        return cid
    return f"{cid} ({c}, https://shopview.testrail.io/index.php?/cases/view/{c[1:]})"

lines = []
A = lines.append
A('# Report Suite — Consolidation (Merge/Cut) Plan — 2026-07-28')
A('')
A('**Companion to:** `USEFULNESS-AUDIT-2026-07-28.md` + `per-case-verdicts.csv` (same folder).')
A('**Source snapshot:** `build/report-suite/cases/*.json` at git SHA `ddf8c16b1c271b12459838f6c9e51a34078087bf` (working tree clean for this folder at snapshot time).')
A('**Status: PROPOSAL ONLY — nothing has been edited.** No case JSON was touched, no TestRail writes were made (Standing Rule 6). The user can approve the whole plan, per-group, or reject it.')
A('')
A('## What this plan does')
A('')
mm = sum(len(m) for _, m, _ in MERGES.values())
A(f'- **{len(MERGES)} merge groups** absorb **{mm} member cases** into their named survivors (the survivor gains the members\' steps/expected lines as a step table — no coverage is lost).')
A(f'- **{len(CUTS)} outright cuts** (no-op assertions, manual-untestable minutiae, literal duplicates).')
A(f'- Result: **515 → {515 - mm - len(CUTS)} cases** with identical behavioral coverage.')
A(f'- A further **{len(WEAK)} WEAK-KEEP** cases are flagged (legitimate but low-value / verify-once); dropping them too would give **{515 - mm - len(CUTS) - len(WEAK)}**. The recommendation is to KEEP them but tag them "build-acceptance / verify once" rather than per-cycle regression.')
A('')
A('Execution note (if approved): this is a TestRail `update_case` (survivor gains steps) + `delete_case` (members/cuts) pass — it requires fresh explicit authorization per Standing Rule 6, a per-case audit log, and regeneration of the import + id-map afterwards. Also reconcile with the pending video-delta rework (serial-number identifier, SBC Print removal, SBC compressed export, location-filter gating) so cases are not edited twice.')
A('')
A('## Merge groups')
A('')
for g, (surv, members, gain) in MERGES.items():
    A(f'### {g}')
    A(f'- **Survivor:** {ref(surv)} — "{titles.get(surv, "?")}"')
    A(f'- **Absorbs:**')
    for m in members:
        A(f'  - {ref(m)} — "{titles.get(m, "?")}" — {MERGE_REASON[m]}')
    A(f'- **What the survivor gains:** {gain}')
    A('')
A('## Cuts')
A('')
for cid, why in CUTS.items():
    A(f'- **{ref(cid)}** — "{titles.get(cid, "?")}" — {why}')
A('')
A('## WEAK-KEEP flags (keep, but verify-once / trim if suite size matters)')
A('')
for cid, why in WEAK.items():
    A(f'- {ref(cid)} — {why}')
A('')
A('---')
A('*Generated by `gen_merge_plan.py` from the same verdict source as `per-case-verdicts.csv` (single source of truth).*')

open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote', OUT, len(lines), 'lines')
