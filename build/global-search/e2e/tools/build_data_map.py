#!/usr/bin/env python3
"""BUILD data/test-data.json — which seeded records every test case needs (QA lead, 2026-10-05).

Three layers, later ones winning where they say more:
  1. each seeded record's own "serves" note (the cases it was created for), in ../seeding;
  2. the search words in data/entity-config.json, retest-plan.json and held-terms-found.json,
     matched to the records that hold them (tools/resolve_terms.py);
  3. data/test-data-manual.json, written by hand for everything the first two cannot see: tests
     that make their own data, tests that need none, chain steps (statuses, purchase orders...).

A need is "<plan>:<record key>" or "<plan>:#<step>" (a step that is not one record: work-order
statuses, purchase orders and invoices, ranking signals). Plans: v1reg gs-v2 ranking toggle pertab e2e.

    python3 tools/build_data_map.py            write data/test-data.json; exit 1 if any case is unmapped
    python3 tools/build_data_map.py --report   also list every case and where its mapping came from

The list of cases comes from Playwright itself (`playwright test --list`), never from a count.
"""
import json, os, re, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
E2E = os.path.dirname(HERE)
DATA = os.path.join(E2E, 'data')
sys.path.insert(0, HERE)
from resolve_terms import manifests, index, holders  # noqa: E402

STEPS = {'gs-v2:#statuses', 'gs-v2:#po-invoices', 'gs-v2:#complete-invoice', 'gs-v2:#roles',
         'gs-v2:#recent', 'ranking:#signals', 'e2e:#po'}

def listed_cases():
    r = subprocess.run(['npx', 'playwright', 'test', '--list', '--reporter=json'], cwd=E2E,
                       capture_output=True, text=True, env={**os.environ, 'GS_SEED': 'skip'})
    d = json.loads(r.stdout)
    out = {}
    def walk(s, f=None):
        f = s.get('file', f)
        for sp in s.get('specs', []):
            cids = re.findall(r'@C(\d{5,6})', sp['title']) or re.findall(r'\bC(\d{5,6})\b', sp['title'])
            for c in cids or [f"title:{sp['title']}"]:
                out.setdefault(c, set()).add(os.path.basename(f))
        for c in s.get('suites', []): walk(c, f)
    for s in d['suites']: walk(s)
    return out

def main():
    report = '--report' in sys.argv
    cases = listed_cases()
    m = {c: {'needs': set(), 'from': set()} for c in cases}
    # 1 · serves notes
    for tag, man in manifests():
        for r in man.get('records', []):
            for c in re.findall(r'\b(\d{5,6})\b', json.dumps(r.get('serves', ''))):
                if c in m: m[c]['needs'].add(f'{tag}:{r["key"]}'); m[c]['from'].add('serves')
    # 2 · configuration search words
    idx = index()
    words = {}
    ec = json.load(open(os.path.join(DATA, 'entity-config.json')))
    for v in ec.values():
        for c in v['cases'].values(): words.setdefault(str(c['cid']), set()).add(c['term'])
        for h in v.get('held', []): words.setdefault(str(h['cid']), set()).add(h['term'])
    for r in json.load(open(os.path.join(DATA, 'retest-plan.json'))): words.setdefault(str(r['cid']), set()).add(r['term'])
    for k, v in json.load(open(os.path.join(DATA, 'held-terms-found.json'))).items():
        if isinstance(v, dict): words.setdefault(k, set()).add(v.get('term'))
    unseeded = {}
    for c, ws in words.items():
        if c not in m: continue
        for w in ws:
            if not w: continue
            h = sorted(set(holders(w, idx)))
            if h: m[c]['needs'] |= set(h); m[c]['from'].add('search word')
            else: unseeded.setdefault(c, set()).add(w)
    # 3 · hand-written
    manual = json.load(open(os.path.join(DATA, 'test-data-manual.json'))) if os.path.exists(os.path.join(DATA, 'test-data-manual.json')) else {}
    for c, v in (manual.get('cases') or {}).items():
        if c not in m: continue
        if v.get('replace'): m[c]['needs'] = set()
        m[c]['needs'] |= set(v.get('needs', [])); m[c]['from'].add('by hand')
        for k in ('own', 'none', 'baseline'):
            if v.get(k): m[c][k] = v[k]
    # validate every need names a real record or step
    known = {f'{t}:{r["key"]}' for t, man in manifests() for r in man.get('records', [])} | STEPS
    bad = sorted({n for v in m.values() for n in v['needs'] if n not in known})
    unmapped = sorted(c for c, v in m.items() if not v['needs'] and not any(v.get(k) for k in ('own', 'none', 'baseline')))
    out = {'_README': 'GENERATED by tools/build_data_map.py - do not edit by hand; edit data/test-data-manual.json '
                      'or a seeded record\'s "serves" note, then re-run it. Which seeded records each test case needs.',
           'cases': {c: {k: (sorted(v) if isinstance(v, set) else v) for k, v in m[c].items() if k != 'from' and v}
                     for c in sorted(m)}}
    json.dump(out, open(os.path.join(DATA, 'test-data.json'), 'w'), indent=1, ensure_ascii=False)
    n = len(m); mapped = n - len(unmapped)
    print(f'{n} cases · {mapped} mapped · {len(unmapped)} unmapped · {len(bad)} unknown needs')
    for w in bad: print(f'  🔴 unknown need: {w}')
    if unseeded:
        print(f'  🔶 {len(unseeded)} case(s) search for a word no seeding plan creates:')
        for c, ws in sorted(unseeded.items()): print(f'     C{c}: {", ".join(sorted(ws))}')
    if report or unmapped:
        for c in unmapped: print(f'  unmapped: C{c}  ({", ".join(sorted(cases[c]))})')
    sys.exit(1 if unmapped or bad else 0)

if __name__ == '__main__':
    main()
