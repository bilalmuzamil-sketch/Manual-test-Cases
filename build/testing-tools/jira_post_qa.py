"""Pre-post gate + upload + post + read-back for a Jira QA comment (Standing Rules 72/81/84/104).

usage: python3 jira_post_qa.py <KEY> <comment.txt> <file1> [<file2> ...] [--expect-build v..] [--prd 63] [--edit <commentId>] [--build-url <url> [--build-cookies <json>]] [--dry]
- --edit updates that comment in place (Rule 100: the text must carry the dated edit note); new files are uploaded first
- re-reads the staging build marker and stops if it differs from --expect-build
- re-reads the ticket (status, assignee, comment count) and the PRD version, stops if --prd differs
- scans the comment text for AI fingerprints / a technical section
- uploads the files as real attachments, posts the wiki-markup comment, reads it back in ADF and prints
  the first block, media (type, size) in order, table rows, numbered-list lengths
Cookies: /tmp/atlassian/cookies.txt (never committed).
"""
import json, re, subprocess, sys

COOK = '/tmp/atlassian/cookies.txt'; J = 'https://shopview.atlassian.net'


def curl(*a):
    r = subprocess.run(['curl', '-s', '-b', COOK, *a], capture_output=True, text=True)
    return r.stdout


def main():
    a = sys.argv[1:]
    opt = lambda k: a[a.index(k) + 1] if k in a else None
    key, ctext = a[0], a[1]
    files = [x for x in a[2:] if not x.startswith('--') and x not in (opt('--expect-build'), opt('--prd'), opt('--edit'), opt('--build-url'), opt('--build-cookies'))]
    # Every embedded picture or film must carry both width and height, or Jira stores it at 183 px high (squashed).
    bad = [m for m in re.findall(r'!([^!|\n]+\.(?:png|jpg|mp4|webm))\|([^!\n]*)!', open(ctext).read()) if 'height=' not in m[1]]
    if bad: sys.exit(f'STOP: embeds without height: {[b[0] for b in bad]}')
    # --build-url <https://svNNNN.qa.shopview.com/> [--build-cookies /tmp/x.json] checks the branch under test (default: staging)
    if opt('--build-url'):
        import subprocess
        ck = json.load(open(opt('--build-cookies'))) if opt('--build-cookies') else {}
        html = subprocess.run(['curl', '-s', '-m', '30', '-H', 'cookie: ' + '; '.join(f'{k}={v}' for k, v in ck.items()), opt('--build-url')], capture_output=True, text=True).stdout
    else:
        html = curl('https://app.staging.shopview.com/index.html')
    build = re.search(r'app-version" content="([^"]+)', html).group(1)
    print('build', build)
    if opt('--expect-build') and build != opt('--expect-build'): sys.exit(f'STOP: build moved to {build}')
    t = json.loads(curl(f'{J}/rest/api/2/issue/{key}?fields=status,assignee,comment,updated'))['fields']
    print('ticket', t['status']['name'], (t['assignee'] or {}).get('displayName'), 'comments', len(t['comment']['comments']),
          [(c['author']['displayName'], c['created'][:16]) for c in t['comment']['comments'][-3:]])
    v = json.loads(curl(f'{J}/wiki/api/v2/pages/845185030'))['version']['number']
    print('prd', v)
    if opt('--prd') and str(v) != opt('--prd'): sys.exit(f'STOP: PRD moved to v{v}')
    body = open(ctext).read(); low = body.lower()
    bad = [b for b in ['claude', 'as an ai', 'anthropic', 'generated by', 'technical details', 'endpoint', 'css'] if b in low]
    if bad: sys.exit(f'STOP: fingerprint/jargon {bad}')
    if opt('--edit') and 'Updated on' not in body: sys.exit('STOP: edit without a dated note (Rule 100)')
    for f in files:
        if f'!{f.split("/")[-1]}' not in body: sys.exit(f'STOP: {f} not referenced in the comment')
    if '--dry' in a: print('dry run OK'); return
    for f in files:
        r = json.loads(subprocess.run(['curl', '-s', '-b', COOK, '-H', 'X-Atlassian-Token: no-check', '-F', f'file=@{f}',
                                       f'{J}/rest/api/3/issue/{key}/attachments'], capture_output=True, text=True).stdout)
        print('uploaded', [(x['id'], x['filename']) for x in r])
    json.dump({'body': body}, open('/tmp/_c.json', 'w'))
    url = f'{J}/rest/api/2/issue/{key}/comment' + (f'/{opt("--edit")}' if opt('--edit') else '')
    r = subprocess.run(['curl', '-s', '-b', COOK, '-H', 'Content-Type: application/json', '-H', 'X-Atlassian-Token: no-check',
                        '-X', 'PUT' if opt('--edit') else 'POST', url, '--data', '@/tmp/_c.json'], capture_output=True, text=True).stdout
    cid = json.loads(r)['id']; print('comment', cid)
    b = json.loads(curl(f'{J}/rest/api/3/issue/{key}/comment/{cid}'))['body']; c = b['content']; o = []
    def w(n):
        if isinstance(n, dict):
            if n.get('type') == 'media': o.append(('media', n['attrs'].get('type'), n['attrs'].get('width'), n['attrs'].get('height')))
            if n.get('type') == 'table': o.append(('table rows', len(n['content'])))
            if n.get('type') == 'orderedList': o.append(('ol', len(n['content'])))
            for k in n.get('content', []): w(k)
    for x in c: w(x)
    first = json.dumps(c[0])
    print('first', c[0]['type'], 'PASSED' if 'PASSED' in first else ('FAILED' if 'FAILED' in first else first[:80]))
    print('readback', o)
    return cid


if __name__ == '__main__':
    main()
