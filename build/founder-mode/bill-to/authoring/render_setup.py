#!/usr/bin/env python3
"""Writes BILL-TO-SETUP-FILE.md: the one setup file for Claude sessions (Rule 117 ninth amendment, kept under the fourteenth). It holds
the environment facts, roles, the recipes that build each kind of record, every case's records with their ZZAUTOTEST names, its PRD
items and marker, the open questions and the held cases. A manual tester never needs it: each case's own preconditions say what must
exist. No secrets: credentials, cookies and API keys live only in /tmp (chmod 600) and are never written here."""
import sys, os, re, json, glob, importlib
D = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, D)
import bt_lib as L
from po_questions import QUESTIONS
_ORDER = [f"cases_s{i}" for i in range(1, 20)] + ["cases_api", "cases_data", "cases_rel", "cases_inv", "cases_design"]
_MODS = sorted(os.path.basename(f)[:-3] for f in glob.glob(f"{D}/cases_*.py"))
for m in [x for x in _ORDER if x in _MODS] + [x for x in _MODS if x not in _ORDER]: importlib.import_module(m)
SECS = json.load(open(f"{L.P}/sections.json"))["sections"]
LAB = re.compile(r"\b(customer|work order|part sale|invoice|asset|contact) ([A-Z]\d?|\d)\b")


def names(c):
    out, k = {}, c["key"]
    for x in c["pre"] + c["steps"]:
        for m in LAB.finditer(x):
            kind, tag = m.group(1), m.group(2)
            lab = f"{kind} {tag}"
            if lab in out: continue
            if kind == "customer": out[lab] = f'customer name "ZZAUTOTEST {k} Customer {tag}"'
            elif kind == "work order": out[lab] = f'work order on customer "ZZAUTOTEST {k} Customer A" unless the case names another; record the number the app assigns'
            elif kind == "part sale": out[lab] = "part sale; record the number the app assigns"
            elif kind == "invoice": out[lab] = "record the invoice number the app assigns"
            elif kind == "asset": out[lab] = f'asset unit "ZZAUTOTEST {k} {tag}" unless the case fixes the unit'
            elif kind == "contact": out[lab] = f'contact "ZZAUTOTEST {k} {tag}", email zzautotest+{k.lower()}-{tag.lower()}@shopview.test (a mailbox the tester can read)'
    return out


R = []; w = R.append
w("# Bill To — setup file for Claude sessions")
w("")
w("Generated by `authoring/render_setup.py` from the case library (9 Nov 2026). **For Claude sessions only: a manual tester never needs this "
  "file** (each case's own preconditions say what must exist). Expected results come only from PRD \"Bill To\" v0.5 (Confluence 1003585538, "
  "6 Nov 2026, pending approval from Mat and Amani, Chris Ward). No secrets are kept here.")
w("")
w("## 1. Environments and accounts")
w("")
w("| What | Value |")
w("|---|---|")
w("| Where the feature lands | **No QA branch is named yet** (QA lead, 9 Nov 2026). The design's after-shots come from \"the locked Bill To build\" (branch `project/bill-to`, snapshot lock_snapshot_20261106_155048). Record the branch and its build marker here when it is given; until then every runnable case carries \"Not available on Build to test Yet\" (Rule 69). |")
w("| Release-day cases (REL section and the cases marked for production) | Production test account, `https://app.shopview.com`; the before-release records are made and noted on production shortly before the release reaches production (Credit terms precedent, QA lead 26 Oct 2026) |")
w("| Sign-in for most cases | An Admin at the test location (holds every permission the PRD names) |")
w("| Permission cases | A custom role per case made from the Admin template with the named permissions switched off: 'Customers → View', 'Customers → Create & Edit', 'Customers → Delete', 'View and Manage AP/AR Data', 'Work orders → View', 'Work orders → Create & Edit', 'Part sales → View', 'Part sales → Create & Edit', 'Invoicing & payments → View', 'See Financial Data', 'View History Logs'. Editing a staff record logs that user out (playbook): finish role changes before signing in as the user |")
w("| Integrations | QuickBooks Online sandbox company connected to the test organization (Story 17); an AccountingHub company the organization sends to (Story 18); IBS connection with account numbers on customers (Story 19, playbook: IBS multi-tenancy needs a feature flag on staging); customer portal with contact logins and a test card (Story 16) |")
w("| Public API | A Public API key for the test organization (kept in `/tmp`), the Public API documentation and a request tool (section API) |")
w("| Counter Sale | The organization's system Counter Sale customer (in the design's data it is named \"Gennadiy's Mobile Truck Repair\"); find its name before running the Counter Sale cases |")
w("| Naming | Every record a case creates is named `ZZAUTOTEST <case key> ...` (section 4) and is removed after the run where the app allows |")
w("")
w("## 2. Recipes (how to build each kind of record)")
w("")
REC = [
 ("Customer that bills itself", "Customers → New Customer → name → leave Bill Invoices To on \"This customer\" → Save."),
 ("Customer with a saved default (\"Bill Invoices To\")", "Edit Customer → Bill Invoices To → pick the payer → Save (needs 'Customers → Create & Edit' and 'View and Manage AP/AR Data'). Do this BEFORE creating the work orders that must start billed to it (S3-R6, S1-R6)."),
 ("Work order billed to someone else, picked by hand", "New Work Order (customer + asset) → open it → expand the Customer card → Bill To → pick the payer (saves at once). Take deposits only AFTER the payer is picked (deposits lock the Bill To)."),
 ("Work order in a status", "Estimate on create; approve a line for Approved; start work for In Progress; Ready for Review; Complete (complete the Review step: playbook \"Complete the Review step\"); Finance → Create Invoice for Invoiced (every part received with a real part number); take a payment for Paid; decline for Declined."),
 ("Deposit", "Work order Finance tab → Add Deposit → Create Deposit (Deposit Date, Payment Method, Deposit Amount, Reference Number, Memo) → Submit Deposit (playbook: Deposits). Reverse it from the same tab."),
 ("Credit term / Credit Hold", "Edit Customer → Credit Terms → Net 30 / Net 15 / COD / Credit Hold (Credit Terms work, SV-11638). Credit Hold and COD force a $0 credit limit."),
 ("Credit limit and amount owed", "Edit Customer → Credit Limit; an unpaid invoice billed to the payer for the stated amount gives what it owes."),
 ("PO is required", "Edit Customer → PO is required (an AP/AR field)."),
 ("Invoice, Reverse, Issue Credit, payment", "Playbook §INVOICING / PAYMENTS: Create Invoice; invoice three-dot → Reverse (needs Work Orders Delete); invoice three-dot → Issue Credit (parts to return); customer Invoices tab → tick rows → New Payment → method → Make Payment."),
 ("Split, reopen", "Work order → Split Work Order (tick lines); part sale → Split Part Sale; a paid work order → reopen onto a new work order."),
 ("Asset with earlier owner", "Create the asset on customer C, make work order 1 for C; move the asset to customer A (Change Customer on a work order associates the vehicle with the new company, playbook), then make work order 2 for A."),
 ("Document layout", "Organization setting for the document design: modern or legacy (the design's renders switched it and set it back to legacy)."),
 ("Two browser tabs", "Open the same work order twice; act in tab 2; return to tab 1 WITHOUT reloading."),
 ("Contacts for email and portal", "Customer → Contacts → add with an email you can read; mark one Billing where the case says; give portal access for Story 16."),
 ("Public API", "Endpoint and field names come from the build's Public API documentation (the PRD names none); record them here once read."),
]
for t, r in REC: w(f"- **{t}:** {r}")
w("")
w("## 3. Questions (drafted, not sent) and held cases")
w("")
for i, (slug, q, basis, opts, holds) in enumerate(QUESTIONS, 1):
    keys = [c["key"] for c in L.CASES if L.qnum(c) == i]
    w(f"- **Question {i}** ({slug}): {q} Held: {', '.join(keys)}.")
for title, pred in (("Blocked on the Internal Work Orders release (SV-11665)", lambda c: c["marker"] == L.IWO_HOLD),
                    ("Blocked on the customer portal app release", lambda c: c["marker"] == L.PORTAL_HOLD),
                    ("Run on production around the release", lambda c: c["marker"] == L.PRE_REL),
                    ("Cannot be forced by hand (NO-MANUAL-PROPOSAL.md)", lambda c: c["held"] and c["marker"] not in (L.IWO_HOLD, L.PORTAL_HOLD, L.PRE_REL) and L.qnum(c) is None)):
    w(f"- {title}: {', '.join(c['key'] for c in L.CASES if pred(c)) or 'none'}.")
w("")
w("## 4. Every case: its records, ZZAUTOTEST names, PRD items and marker")
w("")
for c in L.CASES:
    w(f"### {c['key']} — {c['title']}")
    w(f"Section: {SECS[c['sec']]['name']} · refs {L.refs_of(c)} · PRD items {', '.join(sorted(L.codes_of(c)))} · {c['marker']}")
    if c["banner"]: w(f"**{c['banner']}**")
    w("")
    for p in c["pre"]: w(f"- {p}")
    n = names(c)
    if n:
        w("")
        w("Names to use: " + "; ".join(f"**{k}** = {v}" for k, v in n.items()) + ".")
    w("")
    w("Traceability: " + " · ".join(f"{l}" for l, _ in L.quotes(c)) + ".")
    w("")
open(f"{L.P}/BILL-TO-SETUP-FILE.md", "w").write("\n".join(R) + "\n")
print("BILL-TO-SETUP-FILE.md", len(R), "lines")
