#!/usr/bin/env python3
"""Writes IWO-SETUP-FILE.md: the one setup file for Claude sessions (Rule 117 ninth amendment, kept under the fourteenth). It holds the
environment facts, roles, the recipes that build each kind of record, every case's records with their ZZAUTOTEST names, its PRD items,
marker and folder, the open questions and the held cases. A manual tester never needs it: each case's own preconditions say what must
exist. No secrets: credentials, cookies and API keys live only in /tmp (chmod 600) and are never written here."""
import sys, os, re, json, glob, importlib
D = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, D)
import iwo_lib as L
from po_questions import QUESTIONS
_ORDER = [f"cases_s{i}" for i in range(1, 14)] + ["cases_s12p", "cases_api", "cases_data", "cases_rel", "cases_inv", "cases_design"]
_MODS = sorted(os.path.basename(f)[:-3] for f in glob.glob(f"{D}/cases_*.py"))
for m in [x for x in _ORDER if x in _MODS] + [x for x in _MODS if x not in _ORDER]: importlib.import_module(m)
PROP = json.load(open(f"{D}/proposals.json"))
LAB = re.compile(r"\b(customer|work order|asset|line|category|technician|user|location|part|contact|bill|inspection|reminder|account|period) ([A-Z]\d?|\d)\b")


def names(c):
    out, k = {}, c["key"]
    for x in c["pre"] + c["steps"]:
        for m in LAB.finditer(x):
            kind, tag = m.group(1), m.group(2); lab = f"{kind} {tag}"
            if lab in out: continue
            out[lab] = {"customer": f'customer "ZZAUTOTEST {k} Customer {tag}"',
                        "work order": "record the number the app assigns (the case says whose it is and its state)",
                        "asset": f'asset unit "ZZAUTOTEST {k} Unit {tag}"', "line": f'line title "ZZAUTOTEST {k} Line {tag}"',
                        "category": f'category name "ZZAUTOTEST {k} Cat {tag}"', "technician": f'staff "ZZAUTOTEST {k} Tech {tag}" with the Technician role',
                        "user": f'staff "ZZAUTOTEST {k} User {tag}" with the role the case names', "location": "an existing location of the test organization",
                        "part": f'part number "ZZAUTOTEST-{k}-{tag}"', "contact": f'contact "ZZAUTOTEST {k} {tag}", email zzautotest+{k.lower()}-{tag.lower()}@shopview.test',
                        "bill": "record the vendor bill number the app assigns", "inspection": "an inspection made on the case's asset",
                        "reminder": "a maintenance reminder on the case's asset", "account": "an expense account in the connected company (note its name)",
                        "period": "a fiscal period in Accounting (note its name)"}[kind]
    return out


R = []; w = R.append
w("# Internal Work Orders — setup file for Claude sessions")
w("")
w("Generated by `authoring/render_setup.py` from the case library (12 Nov 2026, round 1). **For Claude sessions only: a manual tester never "
  "needs this file** (each case's own preconditions say what must exist). Expected results come only from PRD \"Internal Work Orders (PRD)\" "
  "Final v1.0 (Confluence 942243841, 9 Nov 2026, Milos Vasic) and, where a case quotes them, the saved Jira tickets of epic SV-11665. "
  "No secrets are kept here.")
w("")
w("## 1. Environments and accounts")
w("")
w("| What | Value |")
w("|---|---|")
w("| Where the feature lands | **No QA branch is named yet** (intake 12 Nov 2026). Record the branch and its build marker here when it is given; until then every runnable case carries \"Not available on Build to test Yet\" (Rule 69). The release has a deploy switch until launch (Jira SV-11973, SV-11981); nothing is visible while it is off. |")
w("| Release-day cases (folder \"Run on Production After Release\") | Production test account, `https://app.shopview.com`; the before-release figures and records are made and noted on production shortly before the release reaches production (Credit terms / Bill To precedent) |")
w("| Sign-in for most cases | An Admin at the test location (holds every permission the PRD names) |")
w("| Permission cases | A custom role per case made from the Admin template with the named permissions switched off: 'Settings — App', 'Settings — Service', 'Settings — Integrations', 'Customers — Create & Edit', 'Work Orders — Create & Edit', 'Work Orders — Delete', 'See Financial Data', 'Invoicing & Payments — Create & Edit', 'Accounting — Settings', 'Reports — Page Access'. Editing a staff record logs that user out (playbook §I): finish role changes before signing in as the user |")
w("| New organization | The one-time turn-on window (Story 1) and the report's first appearance (Story 9) need an organization that never turned the setting on / never closed one: create a new organization per run (playbook §B) |")
w("| QuickBooks Online | A QuickBooks Online sandbox company connected to the test location, with Inventory Asset and Cost of Parts mapped (ShopView Accounts) and the Shop supplies item's income account known. Journal entries are read in QuickBooks (Reports > Journal, or search by work order number). Closed period: QuickBooks Settings > Advanced > Close the books |")
w("| AccountingHub | An organization with AccountingHub enabled; Accounting > Account Mappings, Sales > Invoices, Journal Entries, Accounting Events, fiscal periods |")
w("| Customer portal | A portal contact login for the case's customer and a mailbox the tester can read (approval emails) |")
w("| Open API | An Open API key for the test organization (kept in `/tmp`), the Open API documentation, a request tool and a request-catching page for webhooks. Story 11 waits on SV-11833 |")
w("| Naming | Every record a case creates is named `ZZAUTOTEST <case key> ...` (section 4) and removed after the run where the app allows |")
w("")
w("## 2. Recipes (how to build each kind of record)")
w("")
REC = [
 ("Setting on", "Settings > Work Orders → toggle \"Internal Work Orders\" → Save settings. On an organization where it was never on, the turn-on window opens first: pick the internal customers or \"Do this later\"."),
 ("Internal customer", "Customers → open the customer → Edit Customer → tick \"Internal customer\" (last field) → Default internal category → Save (Make internal window if it has open billable work orders)."),
 ("Category", "Administration > Service > Internal Work Orders → New Internal Category / New No Charge Category → Name, QuickBooks expense account per location, Requires the original work order / Default category → Save. Archive and Restore from the row menu and \"Show archived\"."),
 ("Asset with an Internal category", "Asset → Edit Asset → \"Internal category\" (only on an internal customer's asset, setting on)."),
 ("Internal work order", "New Work Order → pick the internal customer → pick the asset → Save. The category resolves asset → customer → General Internal."),
 ("No Charge work order", "New Work Order → regular customer → asset → tick \"No Charge\" → Category (and Original work order / Original line for Warranty and Comeback) → Save; or Convert to No Charge from the three-dots menu of a billable work order."),
 ("No-charge line", "Billable work order → line three-dots menu → Mark as No Charge → Category (+ originals) → Mark as No Charge; or Edit Line / New Line → tick \"No Charge\"."),
 ("Lines, parts, statuses", "Playbook WORK ORDERS / PARTS: add lines, approve, pick stock parts (cost on the part), order and receive special-order parts, enter the vendor bill, clock in/out, complete lines, Mark Reviewed when review is on."),
 ("Closed internal / no-charge work order", "Complete the lines → Close Work Order (header) → set the posting date if the case names one → Close Work Order in the confirmation."),
 ("Invoiced / paid billable work order", "Create invoice (playbook INVOICING); take a payment for Paid; Reverse from the Finance tab's invoice menu."),
 ("Shop supplies", "Customer Min shop supplies charge on Edit Customer (shown with 'See A/P & A/R data'); the work order's \"Shop supplies\" field with the existing shop supplies control."),
 ("Deposit", "Billable work order → Finance tab → Add Deposit → Submit Deposit (playbook: Deposits)."),
 ("Portal estimate", "Send to Portal from the work order; sign in to the portal as the contact; the \"Approval Required\" email arrives in the contact's mailbox."),
 ("Technician hours", "Clock the technician in and out on the line (Tech View or the line's clock), or add time entries; complete the line."),
]
w("| Record | How |")
w("|---|---|")
for a, b in REC: w(f"| {a} | {b} |")
w("")
w("## 3. Open questions and held cases")
w("")
w("| # | Question (for Milos Vasic) | Cases held |")
w("|---|---|---|")
for i, q in enumerate(QUESTIONS, 1):
    held = [c["key"] for c in L.CASES if L.qnum(c) == i]
    w(f"| {i} | {q[1]} | {', '.join(held)} |")
w("")
w("## 4. Per-case records, items and marker")
w("")
w("Folder: where build.py files the case (story subsection, or WAIT-PO / BLK / PROD). NO-MANUAL cases stay in the library only.")
w("")
for c in L.CASES:
    p = PROP[c["key"]]
    w(f"### {c['key']} — {c['title']}")
    w(f"- Folder: {p['sec']} ({p['section_name']}) · refs {p['refs']} · PRD items: {', '.join(p['codes'])}")
    w(f"- Marker: `{c['marker']}`")
    for lab, val in names(c).items(): w(f"- {lab}: {val}")
    w("")
open(f"{L.P}/IWO-SETUP-FILE.md", "w").write("\n".join(R) + "\n")
print("IWO-SETUP-FILE.md", len(L.CASES), "cases")
