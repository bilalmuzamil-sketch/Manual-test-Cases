#!/usr/bin/env python3
"""Generate every deliverable of the A/R and A/P V1 vs V2 capability check from inventory.py.

    python3 build/ar-ap-report-sorting/v1-regression/tools/build.py

Writes (relative to build/ar-ap-report-sorting/v1-regression/):
  AR-AP-V1-BASELINE.md, INVARIANT-REGISTER.md, what-changed.json, SCOPE.md,
  cases/cases.json, cases/CASES.md, COVERAGE-PROOF.md, POSSIBLE-LOSSES.md
"""
import csv
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import inventory as I  # noqa: E402

PRD_FILE = ROOT / "sources" / "PRD-947650561-v11-2026-11-05.md"
MAP_FILE = ROOT / "sources" / "PRD-SUITE-ID-MAP-group-90418.csv"
HEADER = (
    "> **V1** = " + I.V1_LABEL + ", measured on app.shopview.com 10 and 11 Nov 2026.  \n"
    "> **V2** = " + I.V2_LABEL + " (code); QA branch sv11315 runs it (marker v26.45.2-6a8b89c, exact deployed commit unknown).  \n"
    "> **Intent** = " + I.PRD + " (saved copy `sources/PRD-947650561-v11-2026-11-05.md`; v11 confirmed current via Confluence on 11 Nov 2026).  \n"
    "> **Status of V2 statements:** read from code only. Nothing here was observed on a running V2 build.  \n"
    "> Generated by `tools/build.py` from `tools/inventory.py`. Do not edit by hand.\n"
)


def prd_text():
    return PRD_FILE.read_text(encoding="utf-8")


def prd_requirement(code, text):
    m = re.search(r"^\s*- \*\*" + re.escape(code) + r":\*\* (.+)$", text, re.M)
    if not m:
        raise SystemExit(f"PRD requirement {code} not found")
    return m.group(1).strip()


def quote_of(inv, text):
    q = inv.get("quote")
    if not q:
        return None
    if q.get("ref"):
        return {"doc": I.PRD, "section": q["ref"], "text": prd_requirement(q["ref"], text)}
    return {"doc": I.PRD, "section": q["sec"], "text": q["text"]}


def id_map():
    with MAP_FILE.open(encoding="utf-8") as fh:
        return {r["key"]: r for r in csv.DictReader(fh)}


def existing_txt(keys, idm):
    out = []
    for k in keys:
        r = idm.get(k)
        out.append(f"{k} C{r['case_id']} ({r['link']})" if r else f"{k} (NOT IN MAP)")
    return "; ".join(out)


def main():
    text = prd_text()
    idm = id_map()
    inv_by = {i["id"]: i for i in I.INV}

    # ------------------------------------------------ what-changed.json
    wc = []
    for i in I.INV:
        wc.append({
            "inv": i["id"], "area": i["area"], "reports": i["reports"], "v1": i["v1"],
            "v1_cite": [f"{I.V1_COMMIT}:{c}" for c in i["cite"]], "status": i["status"],
            "v2_code": i["v2"], "quote": quote_of(i, text),
            "cases": i.get("case", []), "existing_prd_suite": i.get("existing", []),
            "reason_no_case": i.get("reason"), "po_question": i.get("po"), "possible_loss": i.get("loss"),
        })
    (ROOT / "what-changed.json").write_text(json.dumps(wc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")

    # ------------------------------------------------ baseline
    b = ["# A/R and A/P aging reports, V1 baseline (what production does today)", "", HEADER,
         "Every behaviour below was read from the product code at the pinned commit. It is FACT about V1, never",
         "an expectation by itself (Rule 57); for the comparison suite V1 IS the specification (Rule 109).",
         "Each line is written for a manual tester: what it means on screen.", ""]
    area = None
    for i in I.INV:
        if i["area"] != area:
            area = i["area"]
            b += ["", f"## {area}", ""]
        b.append(f"- **{i['id']}** ({i['reports']}): {i['v1']}  ")
        b.append("  Source: " + "; ".join(f"`{c}`" for c in i["cite"]))
    b += ["", "## Part B: collateral-risk map", "",
          "See `SCOPE.md` for every shared file the V2 change set touches, what its changed lines do, and whether a screen is IN or OUT.", "",
          "## Part C: existing coverage reused", "",
          "The PRD suite (TestRail group 90418, run 549; id map `sources/PRD-SUITE-ID-MAP-group-90418.csv`, 381 rows, read from the facts branch on 11 Nov 2026) already tests these unchanged behaviours, so no duplicate case was written:", ""]
    used = sorted({k for i in I.INV for k in i.get("existing", [])})
    for k in used:
        r = idm.get(k)
        b.append(f"- {k} C{r['case_id']}: {r['title']}" if r else f"- {k}: NOT IN MAP")
    b += ["", "Unit tests that pin V1 behaviour at fc08f23 (regression anchors, not run here): `" + I.ARF + "test/*.spec.ts`, `" + I.APF + "test/*.spec.ts`, `app/src/router/tests/routeGuards.spec.ts` (SV-8177 block).", "",
          "## Part D: self-check and open ambiguities", "",
          "- Files opened at fc08f23: the six report components, PrintARReportButton.vue, AgingReportModel.ts, ApAgingReportModel.ts, ReportingModel.ts, ReportLeftMenuNav.vue, routes.ts, Reporting.vue, useReportFilters.ts, FilteredTableEmptyState.vue, ReportInfoIcon.vue, utils/helpers.ts and utils/reporting.ts (formatters), useWorkOrderLocationResolver.ts, PartSale.vue, WorkOrder.vue (resolver use); back end: every A/R and A/P class under api/src/Reporting/Dashboard (calculators, domain, handlers, DTOs, controllers, the six Dbal fetchers), OpenBalanceAsOfSql.php, the three A/R PDF templates.",
          "- NOT FOUND IN CODE: the exact on-screen day count for a bill not yet due (depends on how the due date time is stored; open ticket SV-11922); the chip label wording the date chip shows in V1 (the capture shows \"Date: 2026-11-18\").",
          "- Timezone: V1 counts days between UTC timestamps with the as-of set to the end of the browser's local day; V2 counts calendar days in the workplace timezone. Boundary days can differ for a shop far from UTC. Not treated as a loss; boundary cases use whole days well inside a day.",
          "- V1 quirks that the PRD fixes on purpose are registered as CHANGED-BY-DESIGN with the PRD's own sentence (INV-055, INV-079, INV-110)."]
    (ROOT / "AR-AP-V1-BASELINE.md").write_text("\n".join(b) + "\n", encoding="utf-8")

    # ------------------------------------------------ register
    counts = {}
    for i in I.INV:
        counts[i["status"]] = counts.get(i["status"], 0) + 1
    r = ["# Invariant register: A/R and A/P aging, V1 to V2", "", HEADER,
         "Rule: a V1 behaviour is CHANGED-BY-DESIGN or REMOVED-BY-DESIGN only when a PRD, story or PO-answer sentence says so, quoted verbatim below. Silence means MUST NOT CHANGE.", "",
         "| Status | Count |", "|---|---|"]
    for s in ["KEPT", "CHANGED-BY-DESIGN", "REMOVED-BY-DESIGN", "POSSIBLY LOST", "UNCLEAR"]:
        r.append(f"| {s} | {counts.get(s, 0)} |")
    r += [f"| **Total** | **{len(I.INV)}** |", ""]
    for i in I.INV:
        flag = "🔴 " if i["status"] == "POSSIBLY LOST" else ""
        r += [f"## {i['id']} · {flag}{i['status']} · {i['area']}", "",
              f"**V1:** {i['v1']}  ", "**V1 source:** " + "; ".join(f"`{I.V1_COMMIT}:{c}`" for c in i["cite"]) + "  ",
              f"**V2 (code):** {i['v2']}  "]
        q = quote_of(i, text)
        if q:
            r.append(f"**Document:** {q['doc']}, {q['section']}: \"{q['text']}\"  ")
        if i.get("case"):
            r.append("**Case:** " + ", ".join(i["case"]) + "  ")
        if i.get("existing"):
            r.append("**Already tested by the PRD suite:** " + existing_txt(i["existing"], idm) + "  ")
        if i.get("reason"):
            label = "Note" if i.get("case") else "No new case because"
            r.append(f"**{label}:** {i['reason']}  ")
        if i.get("po"):
            r.append(f"**PO question:** {i['po']} (`PO-QUESTIONS.md`)  ")
        r.append("")
    (ROOT / "INVARIANT-REGISTER.md").write_text("\n".join(r) + "\n", encoding="utf-8")

    # ------------------------------------------------ scope
    s = ["# Scope: which screens the A/R and A/P upgrade can change", "", HEADER,
         "Method: every non-test file in the feature diff `411684ac3a..8e35ee0d02` (274 files) was sorted into aging-only or shared. For each shared file the changed lines were read (`git diff 411684ac3a 8e35ee0d02 -- <file>`) and its users were listed at fc08f23 and at the merge base. A screen is IN only when a changed line can run on it.", "",
         "| Screen | Changed file(s) | What the changed lines do | IN / OUT | Why |", "|---|---|---|---|---|"]
    for row in I.SCOPE:
        s.append("| " + " | ".join(x.replace("|", "/") for x in row) + " |")
    s += ["", "Release test plan overlap: Inventory Value, Sales By Customer and Work In Progress are already re-checked by the PRD suite's REL-05, REL-05b, REL-05c, REL-12, REL-12b, REL-12c and REL-13 and by the before-release captures in `../release-2026-11-19/`."]
    (ROOT / "SCOPE.md").write_text("\n".join(s) + "\n", encoding="utf-8")

    # ------------------------------------------------ cases
    cases_out = []
    md = ["# V1 regression cases: A/R and A/P aging reports", "", HEADER,
          "Expected results state the V1 behaviour (Rule 109). Each case's SOURCE line leads with the V1 repository, commit, files and lines, then quotes the V1 code it rests on.", ""]
    for c in I.CASES:
        invs = [inv_by[x] for x in c["inv"]]
        cites = []
        for v in invs:
            for ct in v["cite"]:
                if ct not in cites:
                    cites.append(ct)
        lost = any(v["status"] == "POSSIBLY LOST" for v in invs)
        expected = list(c["exp"])
        if lost:
            expected += [
                "",
                f"EXPECT FAIL. What you should see on the upgraded build today: {c['today']}",
                "(1) You see exactly that: mark the test FAILED and raise nothing new. This is a V1-to-V2 capability loss already reported to the QA lead for a Product Owner decision.",
                "(2) It fails in a different way: that is a new problem. Mark FAILED, write down exactly what you saw, and report it.",
                "(3) It passes: the capability is back. Mark PASSED and tell the QA lead.",
                f"Existing ticket: {c['ticket']}.",
            ]
        source = (f"SOURCE: {I.V1_LABEL}, " + "; ".join(cites) + f". V1 code, quoted: `{c['snip']}`")
        status_doc = ("the A/R and A/P Report Sorting PRD v11 (Confluence 947650561) is silent on it"
                      if lost else "the A/R and A/P Report Sorting PRD v11 (Confluence 947650561) does not change it")
        prov = (f"This is the expected behaviour as per the V1 code baseline AR-AP-V1-BASELINE.md ({', '.join(c['inv'])}) for epic SV-11315; {status_doc}."
                " Not yet checked against any build.")
        if c.get("hold"):
            marker = f"AUTOMATION: HOLD - {c['hold']}"
        elif lost:
            marker = f"AUTOMATION: READY - EXPECT FAIL ({c['symptom']})"
        else:
            marker = "AUTOMATION: READY"
        case = {
            "id": c["id"], "title": c["title"], "section": c["report"],
            "refs": "SV-11315; " + ", ".join(c["inv"]) + "; V1 baseline fc08f23",
            "invariants": c["inv"], "status": "POSSIBLY LOST" if lost else "KEPT",
            "why": c["why"], "data_needs": c["data"],
            "preconditions": c["pre"], "steps": c["steps"], "expected": expected,
            "source": source, "provenance": prov, "marker": marker,
        }
        cases_out.append(case)
        md += [f"## {c['id']} · {c['title']}", "",
               f"Report: {c['report']} · Covers: {', '.join(c['inv'])} · {'🔴 POSSIBLY LOST' if lost else 'KEPT'}", "",
               f"**Why an end user cares:** {c['why']}  ", f"**Data needed:** {c['data']}", "", "**Preconditions**", ""]
        md += [f"{n}. {p}" for n, p in enumerate(c["pre"], 1)]
        md += ["", "**Steps**", ""] + [f"{n}. {p}" for n, p in enumerate(c["steps"], 1)]
        md += ["", "**Expected Result**", ""] + [e if e else "" for e in expected]
        md += ["", "---", "", source, "", prov, "", marker, ""]
    md += ["", "# Planned-change cases (V1R-73 onward)", "",
           "QA lead, 11 Nov 2026: \"If they are planned changes, then OK add tests for them too but in the same folder.\" "
           "Each case quotes the PRD v11 sentence word for word, checks any documented replacement, and checks that the "
           "parts of the V1 behaviour the PRD does not touch are unchanged.", ""]
    for c in I.PLANNED:
        v = inv_by[c["inv"]]
        expected, sections = [], []
        for kind, n, val in c["exp"]:
            if kind == "Q":
                if val in I.QUOTE_TEXT:
                    qt, sec = I.QUOTE_TEXT[val]
                else:
                    qt, sec = prd_requirement(val, text), val
                if sec not in sections:
                    sections.append(sec)
                expected.append(f"Step {n}: PRD v11, {sec}, quoted: \u201c{qt}\u201d")
            elif kind == "O":
                expected.append(f"Step {n} (our restatement, not the PRD's words): {val}")
            else:
                expected.append(f"Step {n} (unchanged from before the release): {val}")
        rel = existing_txt(c["related"], idm)
        expected.append(f"Related existing case: {rel}. This case checks the same planned change from the before-the-release side.")
        cites = list(v["cite"]) + [u for u in c["unchanged"] if u not in v["cite"]]
        source = (f"SOURCE: {I.PRD}, " + "; ".join(sections) + f". V1 behaviour before the change: {I.V1_LABEL}, " + "; ".join(cites) + ".")
        prov = (f"This is the expected behaviour as per the {I.PRD}, " + ", ".join(sections)
                + f", for epic SV-11315; the V1 behaviour it changes is recorded in AR-AP-V1-BASELINE.md ({c['inv']}). Not yet checked against any build.")
        case = {
            "id": c["id"], "title": c["title"], "section": c["report"],
            "refs": f"SV-11315; {c['inv']}; " + ", ".join(sections),
            "invariants": [c["inv"]], "status": v["status"], "why": c["why"], "data_needs": c["data"],
            "preconditions": c["pre"], "steps": c["steps"], "expected": expected,
            "source": source, "provenance": prov, "marker": "AUTOMATION: READY",
        }
        cases_out.append(case)
        md += [f"## {c['id']} · {c['title']}", "",
               f"Report: {c['report']} · Covers: {c['inv']} · {v['status']}", "",
               f"**Why an end user cares:** {c['why']}  ", f"**Data needed:** {c['data']}", "", "**Preconditions**", ""]
        md += [f"{n}. {p}" for n, p in enumerate(c["pre"], 1)]
        md += ["", "**Steps**", ""] + [f"{n}. {p}" for n, p in enumerate(c["steps"], 1)]
        md += ["", "**Expected Result**", ""] + expected
        md += ["", "---", "", source, "", case["provenance"], "", case["marker"], ""]
    (ROOT / "cases").mkdir(exist_ok=True)
    (ROOT / "cases" / "cases.json").write_text(json.dumps(cases_out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    (ROOT / "cases" / "CASES.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    # ------------------------------------------------ coverage proof
    case_ids = {c["id"] for c in I.CASES}
    served = {}
    for c in I.CASES:
        for x in c["inv"]:
            served.setdefault(x, []).append(c["id"])
    for c in I.PLANNED:
        served.setdefault(c["inv"], []).append(c["id"])
    p = ["# Coverage proof: every V1 behaviour has a case, an existing case or a written reason", "", HEADER,
         "| INV | Status | New case(s) | Existing PRD-suite case(s) | Reason when no new case |", "|---|---|---|---|---|"]
    gaps = []
    for i in I.INV:
        new = served.get(i["id"], [])
        if sorted(new) != sorted(i.get("case", [])):
            gaps.append(f"{i['id']}: register says {i.get('case', [])} but cases serve {new}")
        ex = existing_txt(i.get("existing", []), idm) if i.get("existing") else ""
        if not new and not i.get("existing") and not i.get("reason"):
            gaps.append(f"{i['id']}: no case, no existing case, no reason")
        p.append(f"| {i['id']} | {i['status']} | {', '.join(new)} | {ex} | {i.get('reason') or ''} |")
    in_screens = [row for row in I.SCOPE if row[3] == "IN"]
    screen_cases = {
        "core": [c["id"] for c in I.CASES + I.PLANNED if c["report"] not in ("Parts Velocity", "Technician Utilization", "Work In Progress", "Work order", "Part sale")],
        "info": [c["id"] for c in I.CASES if c["report"] in ("Parts Velocity", "Technician Utilization", "Work In Progress")],
        "resolver": [c["id"] for c in I.CASES if c["report"] in ("Work order", "Part sale")],
    }
    p += ["", "## IN screens and their cases", "",
          f"- Core six reports: {len(screen_cases['core'])} cases ({', '.join(screen_cases['core'])}).",
          f"- Parts Velocity, Technician Utilization, Work In Progress: {', '.join(screen_cases['info'])}.",
          f"- Work order and part sale deep links: {', '.join(screen_cases['resolver'])} (plus existing REL-07).", ""]
    for key in screen_cases:
        if not screen_cases[key]:
            gaps.append(f"IN screen group '{key}' has no case")
    by_status = {}
    for i in I.INV:
        by_status[i["status"]] = by_status.get(i["status"], 0) + 1
    p += ["## Counts", "",
          f"- Behaviours (invariants) in the baseline: {len(I.INV)}",
          "- By status: " + ", ".join(f"{k} {v}" for k, v in sorted(by_status.items())),
          f"- New cases: {len(cases_out)}: {len(I.CASES)} regression cases V1R-01..V1R-{len(I.CASES):02d} ({sum(1 for c in cases_out if c['status'] == 'POSSIBLY LOST')} expect-fail or hold for possible losses) and {len(I.PLANNED)} planned-change cases V1R-73..V1R-{72 + len(I.PLANNED)}",
          f"- Behaviours served by a new case: {len(served)}; by an existing PRD-suite case only: {sum(1 for i in I.INV if i['id'] not in served and i.get('existing'))}; by a written reason only: {sum(1 for i in I.INV if i['id'] not in served and not i.get('existing'))}",
          f"- Screens IN: {len(in_screens)} rows in SCOPE.md; OUT: {len(I.SCOPE) - len(in_screens)}",
          f"- Gaps found by this proof: {len(gaps)}"]
    p += [f"  - {g}" for g in gaps]
    (ROOT / "COVERAGE-PROOF.md").write_text("\n".join(p) + "\n", encoding="utf-8")

    # ------------------------------------------------ possible losses
    L = ["# Possible losses: V1 could do it, V2 code appears not to, and no document says it should go", "", HEADER,
         "Every item is inferred from code. None was observed on a running V2 build. Jira was searched (read only) on 11 Nov 2026 for an existing ticket. No ticket was created (Rule 62).", ""]
    losses = {}
    for i in I.INV:
        if i["status"] == "POSSIBLY LOST":
            losses.setdefault(i["loss"], []).append(i)
    for key in sorted(losses):
        items = losses[key]
        cs = sorted({c for i in items for c in i.get("case", [])})
        L += [f"## {key}", ""]
        for i in items:
            L += [f"- **{i['id']}**: {i['v1']}",
                  "  - V1: " + "; ".join(f"`{I.V1_COMMIT}:{c}`" for c in i["cite"]),
                  f"  - V2: {i['v2']}"]
        L += [f"- Cases: {', '.join(cs)}. PO question: {items[0].get('po')}.", ""]
    L += ["## Jira search (read only, 11 Nov 2026)", "",
          "- PL-1 (future as-of date): JQL `text ~ \"aging\" AND (text ~ \"future date\" OR text ~ \"future as-of\" OR text ~ \"after today\" OR text ~ \"later than today\" OR text ~ \"clamp\")`: no ticket about it.",
          "- PL-2 (invoice with no due date): JQL on SV-11315 and \"aging\" with \"credit term\" / \"no due date\" / \"without a due date\": no ticket about it. Related but different: SV-11922 (A/P Past Due one day off), SV-12538 (edited bills show an old due date).",
          "- PL-3 (empty bucket in the Detail PDF): JQL `text ~ \"aging\" AND (text ~ \"empty bucket\" OR ... PDF and bucket)`: no ticket about it."]
    (ROOT / "POSSIBLE-LOSSES.md").write_text("\n".join(L) + "\n", encoding="utf-8")

    print(f"invariants {len(I.INV)}  cases {len(cases_out)}  scope rows {len(I.SCOPE)}  gaps {len(gaps)}")
    return 1 if gaps else 0


if __name__ == "__main__":
    sys.exit(main())
